"""Dev-only: regenerate scripts/es_land.py from Natural Earth 10m land (public domain).

Not used at hack time. Needs shapely and a local copy of ne_10m_land.geojson:

    python tools/build_land_masks.py /path/to/ne_10m_land.geojson
    python tools/build_land_masks.py /path/to/ne_10m_land.geojson --verify
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from shapely.geometry import Point, box, shape
from shapely.ops import unary_union

SKILL_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SKILL_ROOT / "scripts"))

from generate_data import ES_CITIES, MAX_OFFSET_DEG  # noqa: E402

MARGIN_DEG = 0.01
INLAND_BUFFER_DEG = -0.002  # ~200 m: keep jittered homes off the waterline
SIMPLIFY_DEG = 0.0008
MIN_AREA_DEG2 = 1e-5
OUT_PATH = SKILL_ROOT / "scripts" / "es_land.py"


def load_land(path: Path):
    data = json.loads(path.read_text())
    return unary_union([shape(f["geometry"]) for f in data["features"]])


def city_rings(land, city) -> list[list[tuple[float, float]]] | None:
    half = MAX_OFFSET_DEG + MARGIN_DEG
    frame = box(city.lon - half, city.lat - half, city.lon + half, city.lat + half)
    local = land.intersection(frame)
    if local.area / frame.area > 0.999:
        return None
    local = local.buffer(INLAND_BUFFER_DEG).simplify(SIMPLIFY_DEG, preserve_topology=True)
    reach = Point(city.lon, city.lat).buffer(MAX_OFFSET_DEG)
    polys = getattr(local, "geoms", [local])
    rings = []
    for poly in polys:
        if poly.is_empty or poly.area < MIN_AREA_DEG2 or not poly.intersects(reach):
            continue
        rings.append([(round(x, 4), round(y, 4)) for x, y in poly.exterior.coords[:-1]])
    return rings


def write(land) -> None:
    lines = [
        '"""Per-city land polygons (lon, lat) used to keep households out of the sea.',
        "",
        "Generated by tools/build_land_masks.py from Natural Earth 10m land (public domain).",
        "Cities missing here are fully inland within the jitter radius. Do not edit by hand.",
        '"""',
        "",
        "CITY_LAND: dict[str, list[list[tuple[float, float]]]] = {",
    ]
    for city in ES_CITIES:
        rings = city_rings(land, city)
        if rings is None:
            continue
        if not any(Point(city.lon, city.lat).within(shape({"type": "Polygon", "coordinates": [r]})) for r in rings):
            print(f"warning: centre of {city.name} falls outside its mask", file=sys.stderr)
        lines.append(f"    {city.name!r}: [")
        for ring in rings:
            lines.append(f"        {ring!r},")
        lines.append("    ],")
        print(f"{city.name}: {len(rings)} ring(s), {sum(len(r) for r in rings)} vertices")
    lines.append("}")
    OUT_PATH.write_text("\n".join(lines) + "\n")


def verify(land) -> int:
    from generate_data import GenerateConfig, generate_households

    rows = generate_households(GenerateConfig(scale=0.02))
    wet = [h for h in rows if not land.contains(Point(h.lon, h.lat))]
    print(f"{len(wet)} of {len(rows)} households outside Natural Earth land")
    by_city: dict[str, int] = {}
    for h in wet:
        by_city[h.city] = by_city.get(h.city, 0) + 1
    for name, n in sorted(by_city.items(), key=lambda kv: -kv[1]):
        print(f"  {name}: {n}")
    return 1 if len(wet) > len(rows) * 0.001 else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("geojson", type=Path)
    parser.add_argument("--verify", action="store_true")
    args = parser.parse_args(argv)
    land = load_land(args.geojson)
    if args.verify:
        return verify(land)
    write(land)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
